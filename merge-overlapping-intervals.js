// Merge Overlapping Intervals

// وصف المسألة:
// لديك مصفوفة تحتوي على مجموعة من الفترات الرقمية (Intervals).
// كل فترة تتكون من رقمين: الأول بداية الفترة، والثاني نهايتها.
// المطلوب إنشاء دالة mergeIntervals(intervals) تدمج الفترات المتداخلة مع بعضها،
// وتعيد مصفوفة جديدة تحتوي على الفترات بعد الدمج.

// Example 1:
// intervals = [[1, 3], [2, 6], [8, 10], [15, 18]] → [[1, 6], [8, 10], [15, 18]]
// الفترتان [1, 3] و[2, 6] تشتركان في الأرقام من 2 إلى 3، فندمجهما في [1, 6].
// أما [8, 10] و[15, 18] فلا تتداخلان مع أي فترة أخرى، ولذلك تبقيان كما هما.

// Example 2:
// intervals = [[1, 4], [4, 5]] → [[1, 5]]

// Example 3:
// intervals = [[5, 7], [1, 3], [2, 6]] → [[1, 7]]

// Example 4:
// intervals = [[1, 10], [2, 3], [4, 8]] → [[1, 10]]

// الشروط:

// كل فترة تحتوي على رقمين فقط [start, end]، ويكون start <= end.
// إذا تداخلت فترتان، يجب دمجهما في فترة واحدة تغطيهما بالكامل.
// إذا كانت نهاية فترة تساوي بداية فترة أخرى، فإنهما تعتبران متداخلتين.
// قد تكون الفترات غير مرتبة داخل المصفوفة.
// قد تحتوي فترة على فترة أخرى بالكامل.
// إذا كانت المصفوفة فارغة، أعد [].
// يجب أن تكون الفترات في النتيجة مرتبة تصاعديًا حسب قيمة البداية.

function mergeIntervals(obj) {
  if (obj.length === 0) {
    return [];
  }

  let arr = obj.sort((a, b) => a[0] - b[0]);

  for (let i = 0; i < arr.length - 1; i++) {
    if (arr[i][1] >= arr[i + 1][0]) {
      if (arr[i][1] <= arr[i + 1][1]) {
        arr[i][1] = arr[i + 1][1];
      }
      arr.splice(i + 1, 1);
      i--;
    }
  }

  return arr;
}

